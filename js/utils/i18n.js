export const LANGS = ["es", "en"];

function readLang() {
  try {
    const l = localStorage.getItem(LANG_KEY);
    return LANGS.includes(l) ? l : "es";
  } catch {
    return "es";
  }
}

let current = readLang();
const listeners = new Set();

export function getLang() {
  return current;
}

export function setLang(lang) {
  if (!LANGS.includes(lang) || lang === current) return;
  current = lang;
  try { localStorage.setItem(LANG_KEY, lang); } catch { /* sin almacenamiento */ }
  document.documentElement.lang = lang;
  applyStatic();
  listeners.forEach(fn => fn(lang));
}

export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/** Traduce una clave; {n} se sustituye con params.n */
export function t(key, params = {}) {
  const str = DICT[current][key] ?? DICT.es[key] ?? key;
  return str.replace(/\{(\w+)\}/g, (_, k) => (k in params ? params[k] : `{${k}}`));
}

/** Aplica traducciones a elementos con data-i18n / data-i18n-title */
export function applyStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-title]").forEach(el => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute("aria-label", el.title);
  });
}

